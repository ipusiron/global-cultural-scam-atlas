/**
 * Look up a message by key with a safe fallback.
 * Uses `in` so that explicitly-empty translations also apply.
 */
export function t(locale, key){
  const dict = messages[locale] || messages.ja;
  if(key in dict) return dict[key];
  if(key in messages.ja) return messages.ja[key];
  return key;
}

/**
 * Localise a controlled-vocabulary value. Returns the value itself if the
 * dictionary has no entry for it, so unknown values stay visible.
 */
export function labelFor(prefix, value, locale){
  const key = `${prefix}.${value}`;
  const dict = messages[locale] || messages.ja;
  if(key in dict) return dict[key];
  if(key in messages.ja) return messages.ja[key];
  return value;
}
